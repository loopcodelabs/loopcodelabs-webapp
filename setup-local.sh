# --- STEP 5,6 & 7: MYSQL DATABASE SETUP & SCHEMA MIGRATION ---
echo -e "\n${BLUE}[Step 5/14] Provisioning MySQL Databases & Running Migrations...${NC}"

init_db_from_env() {
    local env_file=$1
    local env_label=$2

    if [ ! -f "$env_file" ]; then
        return 0
    fi

    echo -e "${CYAN}--- Checking Database Configuration for $env_label ($env_file) ---${NC}"

    local h p u pass name
    h=$(grep -E '^DB_HOST=' "$env_file" | head -n 1 | cut -d '=' -f2- | tr -d '"' | tr -d "'" | tr -d '\r')
    p=$(grep -E '^DB_PORT=' "$env_file" | head -n 1 | cut -d '=' -f2- | tr -d '"' | tr -d "'" | tr -d '\r')
    u=$(grep -E '^DB_USER=' "$env_file" | head -n 1 | cut -d '=' -f2- | tr -d '"' | tr -d "'" | tr -d '\r')
    pass=$(grep -E '^DB_PASSWORD=' "$env_file" | head -n 1 | cut -d '=' -f2- | tr -d '"' | tr -d "'" | tr -d '\r')
    name=$(grep -E '^DB_NAME=' "$env_file" | head -n 1 | cut -d '=' -f2- | tr -d '"' | tr -d "'" | tr -d '\r')

    if [ -z "$h" ] || [ -z "$name" ] || [[ "$h" == *"your-"* ]]; then
        echo -e "${YELLOW}  [-] Skipping $env_file: Contains placeholder host ('$h') or incomplete config.${NC}"
        return 0
    fi

    echo " Host     : $h"
    echo " Port     : ${p:-3306}"
    echo " User     : $u"
    echo " Database : $name"

    if ! command -v mysql >/dev/null 2>&1; then
        echo -e "${YELLOW}  [-] MySQL client is not installed. Skipping database initialization.${NC}"
        return 0
    fi

    if MYSQL_PWD="$pass" mysqladmin -h "$h" -P "${p:-3306}" -u "$u" ping --silent >/dev/null 2>&1; then
        echo -e "${GREEN}  [✓] MySQL server detected at $h:${p:-3306}.${NC}"
        echo -e "${CYAN}  Creating database '$name' if not exists...${NC}"

        MYSQL_PWD="$pass" mysql -h "$h" -P "${p:-3306}" -u "$u" -e "CREATE DATABASE IF NOT EXISTS \`$name\` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;"

        echo -e "${GREEN}  [✓] Database '$name' ready.${NC}"

        if [ -f "scripts/schema.sql" ]; then
            MYSQL_PWD="$pass" mysql -h "$h" -P "${p:-3306}" -u "$u" "$name" < scripts/schema.sql
            echo -e "${GREEN}  [✓] Schema imported into '$name'.${NC}"
        fi

        if [ -f "scripts/seed.sql" ]; then
            MYSQL_PWD="$pass" mysql -h "$h" -P "${p:-3306}" -u "$u" "$name" < scripts/seed.sql
            echo -e "${GREEN}  [✓] Seed data imported into '$name'.${NC}"
        fi
    else
        echo -e "${YELLOW}  [-] Unable to connect to MySQL server at $h:${p:-3306}.${NC}"
        echo -e "${YELLOW}      Application will use local fallback analyticsStore.ts if live DB is unavailable.${NC}"
    fi
}

init_db_from_env ".env" "Development"
