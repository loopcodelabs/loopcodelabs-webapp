# Check Essential System Commands
check_tool() {
    local tool=$1
    if command -v "$tool" &> /dev/null; then
        local ver=""
        if [ "$tool" = "openssl" ]; then
            ver=$(openssl version 2>&1 | head -n 1)
        else
            ver=$(eval "$tool --version 2>&1 | head -n 1" || true)
        fi
        echo -e "${GREEN}  [✓] $tool is installed (${NC}$ver${GREEN})${NC}"
        return 0
    else
        echo -e "${YELLOW}  [!] $tool is missing or not in PATH.${NC}"
        return 0
    fi
}

