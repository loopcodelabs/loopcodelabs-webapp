# --- STEP 1: OPERATING SYSTEM & ENVIRONMENT VALIDATION ---
echo -e "${BLUE}[Step 1/14] Detecting Operating System & Environment...${NC}"

OS_TYPE="Unknown"
if [ -f /etc/os-release ]; then
    . /etc/os-release
    OS_TYPE=$NAME
elif [[ "$OSTYPE" == "darwin"* ]]; then
    OS_TYPE="macOS"
fi

if grep -q -i microsoft /proc/version 2>/dev/null; then
    OS_TYPE="$OS_TYPE (WSL2)"
fi

echo -e "${GREEN}✓ Detected OS: ${BOLD}$OS_TYPE${NC}"

# Check Essential System Commands
check_tool() {
    local tool=$1
    if command -v "$tool" &> /dev/null; then
        local ver=""
        if [ "$tool" = "openssl" ]; then
            ver=$(openssl version 2>&1 | head -n 1)
        else
            ver=$(eval "$tool --version 2>&1 | head -n 1" || true)
        fi
        echo -e "${GREEN}  [✓] $tool is installed (${NC}$ver${GREEN})${NC}"
        return 0
    else
        echo -e "${YELLOW}  [!] $tool is missing or not in PATH.${NC}"
        return 0
    fi
}

echo -e "${CYAN}Checking required system dependencies:${NC}"
check_tool "git"
check_tool "node"
check_tool "npm"
check_tool "openssl"
check_tool "curl"
check_tool "make"
check_tool "mysql" || echo -e "${YELLOW}      (MySQL client optional if using local Node.js analytics store)${NC}"
check_tool "docker" || true
check_tool "docker-compose" || true
check_tool "python3" || true

# Package Manager Detection
PKG_MANAGER="npm"
if command -v bun &> /dev/null; then
    PKG_MANAGER="bun"
    echo -e "${GREEN}  [✓] Bun runtime detected! Using bun for high-speed package management.${NC}"
fi

# --- STEP 2: VERIFY PROJECT REPOSITORY ---
echo -e "\n${BLUE}[Step 2/14] Verifying Project Workspace...${NC}"
if [ -d ".git" ]; then
    echo -e "${GREEN}✓ Local Git repository confirmed.${NC}"
    git status -s || true
else
    echo -e "${YELLOW}✓ Running in standalone workspace mode.${NC}"
fi

# --- STEP 3: INSTALL PROJECT DEPENDENCIES ---
echo -e "\n${BLUE}[Step 3/14] Installing Node.js & Application Dependencies...${NC}"
if [ "$PKG_MANAGER" = "bun" ]; then
    bun install
else
    npm install
fi
echo -e "${GREEN}✓ All dependencies verified & installed successfully.${NC}"

# --- STEP 4: ENVIRONMENT CONFIGURATION FILES & SECRET GENERATION ---
echo -e "\n${BLUE}[Step 4/14] Generating Environment Files & Dynamic Secrets...${NC}"

gen_secret() {
    if command -v openssl &> /dev/null; then
        openssl rand -hex 32
    else
        head -c 32 /dev/urandom | base64 | tr -dc 'a-zA-Z0-9' | head -c 32
    fi
}

JWT_SEC=$(gen_secret)
ENC_KEY=$(gen_secret)
SESS_SEC=$(gen_secret)
COOKIE_SEC=$(gen_secret)

create_env_file() {
    local target_file=$1
    local env_name=$2
    if [ ! -f "$target_file" ]; then
        cat <<EOF > "$target_file"
# Environment Configuration: $env_name
# Auto-generated by setup-local.sh on $(date)

NODE_ENV=$env_name
PORT=3000
APP_URL="http://localhost:3000"

# Security & Session Keys (Auto-Generated)
JWT_SECRET="$JWT_SEC"
ENCRYPTION_KEY="$ENC_KEY"
SESSION_SECRET="$SESS_SEC"
COOKIE_SECRET="$COOKIE_SEC"

# Database Configuration (MySQL)
DB_HOST="localhost"
DB_PORT=3306
DB_USER="loopcodelabs_user"
DB_PASSWORD="LoopCodeDevPassword123!"
DB_NAME="loopcodelabs_dev"

# Google & Optional API Keys
GEMINI_API_KEY=""
GOOGLE_CLIENT_ID=""
GOOGLE_CLIENT_SECRET=""
ALLOWED_EMAILS=""
GOOGLE_SITE_VERIFICATION=""
EOF
        echo -e "${GREEN}  [✓] Created $target_file ($env_name environment)${NC}"
    else
        echo -e "${YELLOW}  [-] $target_file already exists (Skipping overwrite to protect custom variables).${NC}"
    fi
}

create_env_file ".env" "development"
create_env_file ".env.dev" "development"
create_env_file ".env.stage" "staging"
create_env_file ".env.prod" "production"

